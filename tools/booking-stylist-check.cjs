const { chromium } = require('playwright');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route(/https:\/\/(fonts\.googleapis|fonts\.gstatic|cdn\.jsdelivr)/, r => r.abort());
    await page.goto('http://127.0.0.1:5184/booking');
    const check = name => page.locator(`.service-checkbox[data-name="${name}"]`);
    const wait = async (fn, message) => { for (let i = 0; i < 100; i++) { if (await fn()) return; await page.waitForTimeout(50); } throw Error(message); };
    await check('Demo Cắt tóc').check();
    await wait(async () => await page.locator('#stylist-options button:not([data-any-stylist])').count() === 3, 'Expected three stylists');
    await check('Demo Gội đầu').check();
    await wait(async () => await page.locator('#stylist-options button:not([data-any-stylist])').count() === 2, 'Expected two stylists');
    const anyButton = page.getByRole('button', { name: 'Thợ bất kỳ', exact: true });
    if (await page.locator('#selected-stylist').inputValue()) throw Error('Any stylist must be explicitly selected');
    if (await page.locator('#stylist-options button').first().innerText() !== 'Thợ bất kỳ') throw Error('Any must be first');
    const today = await page.locator('#booking-date').inputValue();
    const tomorrow = new Date(today + 'T12:00:00Z'); tomorrow.setUTCDate(tomorrow.getUTCDate() + 1);
    await page.locator('#booking-date').fill(tomorrow.toISOString().slice(0, 10));
    await page.getByRole('button', { name: 'Demo Thợ A', exact: false }).click();
    await wait(async () => await page.locator('#slot-options button').count() > 0, 'A slots');
    if (await page.locator('#slot-options').getByRole('button', { name: '09:00 – 10:00', exact: true }).count()) throw Error('A shows B-only slot');
    await page.locator('#slot-options').getByRole('button', { name: '10:00 – 11:00', exact: true }).click();
    await page.getByRole('button', { name: 'Demo Thợ B', exact: false }).click();
    await wait(async () => await page.locator('#slot-options').getByRole('button', { name: '09:00 – 10:00', exact: true }).count() === 1, 'B slots');
    if (await page.locator('#selected-slot').inputValue()) throw Error('Old slot retained');
    // Any is the sorted, deduplicated union and must include both exclusive slots.
    await anyButton.click();
    await wait(async () => await page.locator('#slot-options').getByRole('button', { name: '10:00 – 11:00', exact: true }).count() === 1, 'Any union');
    const merged = await page.locator('#slot-options button').allTextContents();
    if (!merged.includes('09:00 – 10:00') || merged.includes('09:15 – 10:15') || new Set(merged).size !== merged.length) throw Error('Invalid union');
    if (merged.join() !== [...merged].sort().join()) throw Error('Unsorted slots');
    const fullDay = new Date(tomorrow); fullDay.setUTCDate(fullDay.getUTCDate() + 1);
    await page.locator('#booking-date').fill(fullDay.toISOString().slice(0, 10));
    await page.getByRole('button', { name: 'Demo Thợ A', exact: false }).click();
    await wait(async () => (await page.locator('#slot-message').innerText()).includes('không còn khung giờ'), 'A fully booked');
    if (await page.locator('#slot-options button').count()) throw Error('Booked A has slots');
    await anyButton.click();
    await wait(async () => await page.locator('#slot-options button').count() > 0, 'Any should show B availability');
    await page.locator('#slot-options button').first().click();
    if (!await page.locator('#selected-slot').inputValue() || await page.locator('#selected-stylist').inputValue() !== '0') throw Error('Any selection assigned a stylist');
    await page.getByRole('button', { name: 'Demo Thợ A', exact: false }).click();
    await wait(async () => (await page.locator('#slot-message').innerText()).includes('không còn khung giờ'), 'Switch back to full A');
    if (await page.locator('#selected-slot').inputValue()) throw Error('Union slot retained for full A');
    await page.locator('#booking-date').fill(tomorrow.toISOString().slice(0, 10));
    await page.getByRole('button', { name: 'Demo Thợ A', exact: false }).click();
    await check('Demo Nhuộm tóc').check();
    await wait(async () => await page.locator('#stylist-options button:not([data-any-stylist])').count() === 1, 'Dye should remove A');
    if (await page.locator('#selected-stylist').inputValue() || await page.locator('#slot-options button').count()) throw Error('Invalid selection retained');
    await check('Demo Không có thợ').check();
    await wait(async () => (await page.locator('#stylist-message').innerText()).includes('Không có thợ nào'), 'Empty state');
    if (!await anyButton.isDisabled()) throw Error('Any should be disabled without qualified stylists');
    await page.getByRole('button', { name: 'Bỏ chọn tất cả', exact: false }).click();
    if (await page.locator('#stylist-selection').isVisible()) throw Error('Panel should hide');
    // Delayed old request must not overwrite a newer service selection.
    await page.route('**/booking/stylists?*', async route => {
      const response = await route.fetch();
      if (new URL(route.request().url()).searchParams.getAll('serviceIds').length === 1) await new Promise(r => setTimeout(r, 500));
      await route.fulfill({ response }).catch(() => {});
    });
    await check('Demo Cắt tóc').check(); await check('Demo Nhuộm tóc').check();
    await wait(async () => await page.locator('#stylist-options button:not([data-any-stylist])').count() === 1, 'Latest response');
    await page.waitForTimeout(700);
    if (await page.locator('#stylist-options button:not([data-any-stylist])').count() !== 1) throw Error('Stale response rendered');
    await page.getByRole('button', { name: 'Demo Thợ B', exact: false }).click();
    await wait(async () => await page.locator('#slot-options button').count() > 0, 'Final slots');
    const later = new Date(tomorrow); later.setUTCDate(later.getUTCDate() + 8);
    await page.locator('#booking-date').fill(later.toISOString().slice(0, 10));
    await wait(async () => (await page.locator('#slot-message').innerText()).includes('không còn khung giờ'), 'Date change must refresh slots');
    if (await page.locator('#slot-options button').count()) throw Error('Old slots persisted after date change');
    await page.locator('#booking-date').fill(tomorrow.toISOString().slice(0, 10));
    await wait(async () => await page.locator('#slot-options button').count() > 0, 'Date restored');
    // Confirm any-stylist assignment using the workload demo, then invalidate on edits.
    await check('Demo Nhuộm tóc').uncheck();
    await wait(async () => await page.locator('#stylist-options button:not([data-any-stylist])').count() === 3, 'Cut-only candidates');
    const workloadDay = new Date(tomorrow); workloadDay.setUTCDate(workloadDay.getUTCDate() + 2);
    await page.locator('#booking-date').fill(workloadDay.toISOString().slice(0, 10));
    await anyButton.click();
    await wait(async () => await page.locator('#slot-options').getByRole('button', { name: '14:00 – 14:30', exact: true }).count() === 1, 'Workload slots');
    await page.locator('#slot-options').getByRole('button', { name: '14:00 – 14:30', exact: true }).click();
    await page.getByRole('button', { name: 'Xác nhận lựa chọn', exact: true }).click();
    await wait(async () => (await page.locator('#assignment-message').innerText()).includes('Demo Thợ C'), 'Least-loaded C');
    await check('Demo Gội đầu').check();
    await wait(async () => await page.locator('#slot-options').getByRole('button', { name: '14:00 – 15:00', exact: true }).count() === 1, 'Wash narrows candidates');
    if (await page.locator('#assignment-confirmation').isVisible()) throw Error('Old assignment retained');
    await page.locator('#slot-options').getByRole('button', { name: '14:00 – 15:00', exact: true }).click();
    await page.getByRole('button', { name: 'Xác nhận lựa chọn', exact: true }).click();
    await wait(async () => (await page.locator('#assignment-message').innerText()).includes('Demo Thợ B'), 'Next least-loaded B');
    const tieDay = new Date(workloadDay); tieDay.setUTCDate(tieDay.getUTCDate() + 1);
    await page.locator('#booking-date').fill(tieDay.toISOString().slice(0, 10));
    await wait(async () => await page.locator('#slot-options').getByRole('button', { name: '14:00 – 15:00', exact: true }).count() === 1, 'Tie day slots');
    await page.locator('#slot-options').getByRole('button', { name: '14:00 – 15:00', exact: true }).click();
    await page.getByRole('button', { name: 'Xác nhận lựa chọn', exact: true }).click();
    await wait(async () => (await page.locator('#assignment-message').innerText()).includes('Demo Thợ A'), 'Stable tie A');
    if (await page.locator('#selected-stylist').inputValue() !== '0') throw Error('Assignment overwrote any selection');
    fs.mkdirSync('artifacts/booking', { recursive: true });
    await page.locator('#stylist-selection').screenshot({ path: 'artifacts/booking/stylist-selection.png' });
    if (errors.length) throw Error(JSON.stringify(errors));
    console.log('PASS: skills intersection, stylist-specific slots, change selection, invalidation, empty state, clear, stale-response protection; no JS errors.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
